const findMult = function(aq, atm = 1.0, stop = 10, error_tol = .01) {
  if (stop <= 0) { return(atm); }
  let mult = atm;  let csum = 0.0;
  for (let ii = 0; ii < aq.length; ii++) {
    csum += Math.floor(aq[ii] * mult) - (aq[ii]*mult)
  }
  if (abs(csum) < error_tol) {  return(atm) 
  } else {
    return(findMult(aq, atm*10, stop - 1));
  }
}
